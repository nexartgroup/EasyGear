-- Items.lua: item data, loading and caching
return function(T)
    local F = require("fixtures")

    T.test("items: data of a cached item", function()
        local W = T.world(F.ARMS)
        local link = F.gear(W, 3001, "Test Chest", "INVTYPE_CHEST", 40, { STR = 30, STA = 40 },
            { armor = 500, minLevel = 35, sockets = 1, sellPrice = 123 })
        local it = W.EG.Items.Get(link)
        T.ok(it, "item")
        T.eq(it.id, 3001) T.eq(it.name, "Test Chest") T.eq(it.ilvl, 40) T.eq(it.equipLoc, "INVTYPE_CHEST")
        T.eq(it.isGear, true) T.eq(it.stats.STR, 30) T.eq(it.stats.STA, 40) T.eq(it.stats.ARMOR, 500)
        T.eq(it.sockets, 1) T.eq(it.reqLevel, 35) T.eq(it.usable, true) T.eq(it.sellPrice, 123)
        T.eq(it.slotText, "Chest")
    end)

    T.test("items: a number works like a link", function()
        local W = T.world(F.ARMS)
        F.gear(W, 3002, "By Id", "INVTYPE_HEAD", 20, { INT = 5 })
        T.eq(W.EG.Items.Get(3002).name, "By Id")
    end)

    T.test("items: uncached items return nil and loading, and ask the client once", function()
        local W = T.world(F.ARMS)
        local link = F.gear(W, 3003, "Slow", "INVTYPE_CHEST", 40, { STR = 1 }, { uncached = true })
        local it, why = W.EG.Items.Get(link)
        T.eq(it, nil) T.eq(why, "loading")
        W.EG.Items.Get(link)
        T.eq(#W.state.loadRequests, 1, "requested once")
        T.eq(W.state.loadRequests[1], 3003)
    end)

    T.test("items: GET_ITEM_INFO_RECEIVED announces ITEMS_LOADED after a short delay", function()
        local W = T.world(F.ARMS)
        local fired = 0
        W.EG:Listen("ITEMS_LOADED", function() fired = fired + 1 end)
        W.fire("GET_ITEM_INFO_RECEIVED", 3003)
        W.fire("GET_ITEM_INFO_RECEIVED", 3004)
        T.eq(fired, 0)
        W.flush()
        T.eq(fired, 1, "debounced to one event")
    end)

    T.test("items: invalid input", function()
        local W = T.world(F.ARMS)
        local it, why = W.EG.Items.Get(nil)
        T.eq(it, nil) T.eq(why, "invalid")
        it, why = W.EG.Items.Get("")
        T.eq(why, "invalid")
        it, why = W.EG.Items.Get(999999)
        T.eq(it, nil) T.eq(why, "loading")
    end)

    T.test("items: non-gear and cosmetic items are not gear", function()
        local W = T.world(F.ARMS)
        local potion = F.gear(W, 3010, "Potion", "", 10, {})
        T.eq(W.EG.Items.Get(potion).isGear, false)
        local cosmetic = F.gear(W, 3011, "Cosmetic Hat", "INVTYPE_HEAD", 10, {}, { cosmetic = true })
        T.eq(W.EG.Items.Get(cosmetic).isGear, false)
    end)

    T.test("items: client marks unusable items", function()
        local W = T.world(F.ARMS)
        local link = F.gear(W, 3012, "Cloth Robe", "INVTYPE_CHEST", 40, { INT = 30 }, { badType = true, typeText = "Cloth" })
        local it = W.EG.Items.Get(link)
        T.eq(it.usable, false)
        T.eq(it.reason, W.EG.L.R_CLASS)
    end)

    T.test("items: weapons carry dps and hand kind", function()
        local W = T.world(F.ARMS)
        local sword = F.gear(W, 3013, "Blade", "INVTYPE_WEAPON", 30, {}, { dps = 20.5 })
        local it = W.EG.Items.Get(sword)
        T.eq(it.dps, 20.5) T.eq(it.handKind, "MELEE")
        local bow = F.gear(W, 3014, "Bow", "INVTYPE_RANGED", 30, {}, { dps = 12 })
        T.eq(W.EG.Items.Get(bow).handKind, "RANGED")
    end)

    T.test("items: effective item level (upgrades) comes from GetDetailedItemLevelInfo", function()
        local W = T.world(F.ARMS)
        local link = F.gear(W, 3015, "Upgraded", "INVTYPE_HEAD", 40, {}, { effectiveIlvl = 55 })
        local it = W.EG.Items.Get(link)
        T.eq(it.ilvl, 55) T.eq(it.baseIlvl, 40)
    end)

    T.test("items: results are cached and cleared when enchant counting changes", function()
        local W = T.world(F.ARMS)
        local link = F.gear(W, 3016, "Enchanted", "INVTYPE_CHEST", 40, { STR = 10 },
            { lines = { { type = T.Mock.LINE.ItemEnchantmentPermanent, leftText = "Enchanted: +15 Stamina", leftColor = T.Mock.COLOR.green } } })
        local a = W.EG.Items.Get(link)
        T.ok(W.EG.Items.Get(link) == a, "same table from the cache")
        T.eq(a.stats.STA, 15)
        W.EG:Set("includeEnchants", false)
        local b = W.EG.Items.Get(link)
        T.ok(b ~= a, "rebuilt")
        T.eq(b.stats.STA, nil)
    end)

    T.test("items: equipped item helpers", function()
        local W = T.world(F.ARMS)
        local link = F.gear(W, 3017, "Worn", "INVTYPE_CHEST", 40, { STR = 10 })
        W.equip(5, link)
        T.eq(W.EG.Items.EquippedLink(5), link)
        T.eq(W.EG.Items.Equipped(5).name, "Worn")
        T.eq(W.EG.Items.Equipped(6), nil)
    end)
end
