-- Score.lua: scoring and comparison. Baseline: level 60 arms warrior, ilvl weight 0.5, worn set with known scores
--   chest 44.5   ring1 32.5   ring2 14.5   trinket 35   main hand 175
return function(T)
    local F = require("fixtures")

    local function arms(extra, setup)
        return T.world(F.arms(extra), function(W)
            W.I = F.armsWarrior(W)
            if setup then setup(W) end
        end)
    end
    local function compare(W, link, detail)
        local r, why = W.EG.Score.Compare(link, detail)
        T.ok(r, "compare failed: " .. tostring(why))
        return r
    end
    local function betterChest(W)
        return F.gear(W, 4001, "Better Chestplate", "INVTYPE_CHEST", 40, { STR = 30, STA = 40, CRIT = 20 },
            { armor = 500, minLevel = 35 })
    end

    T.test("score: worn set has the expected scores", function()
        local W = arms()
        local S, I = W.EG.Score, W.I
        T.eq(W.EG.Profiles.Resolve().spec.id, "WARRIOR_ARMS")
        T.near(S.OfLink(I.chest), 44.5) T.near(S.OfLink(I.ring1), 32.5) T.near(S.OfLink(I.ring2), 14.5)
        T.near(S.OfLink(I.trinket), 35) T.near(S.OfLink(I.sword), 175)
    end)

    T.test("score: breakdown rows add up and are labelled", function()
        local W = arms()
        local rows, total = W.EG.Score.Breakdown(W.EG.Items.Get(W.I.chest))
        T.near(total, 44.5)
        local sum, byKey = 0, {}
        for _, r in ipairs(rows) do sum = sum + r.points byKey[r.key] = r end
        T.near(sum, 44.5)
        T.eq(rows[1].key, "ILVL") T.eq(byKey.STR.label, "Strength") T.near(byKey.STR.points, 20)
        T.near(byKey.ARMOR.points, 7.5) T.near(byKey.STA.points, 2)
    end)

    T.test("score: chest upgrade - gain, percent, replaced item and attribute differences", function()
        local W = arms()
        local r = compare(W, betterChest(W), true)
        T.near(r.score, 81.5) T.near(r.targetScore, 44.5) T.near(r.delta, 37)
        T.near(r.percent, 37 / 44.5 * 100, 1e-6)
        T.eq(r.isUpgrade, true) T.eq(r.usable, true) T.eq(r.mode, "SINGLE") T.eq(r.slotName, "Chest")
        T.eq(r.replaced[1].item.name, "Worn Chestplate")
        T.near(r.breakdown[1].points, 20)
        local diffs = W.EG.Score.StatDiff(r.item, r.replaced)
        T.eq(diffs[1].key, "CRIT") T.near(diffs[1].delta, 20)
        T.eq(diffs[2].key, "STR") T.near(diffs[2].delta, 10)
    end)

    T.test("score: weaker and equal items are no upgrade and say why", function()
        local W = arms()
        local weak = F.gear(W, 4002, "Weak Chestplate", "INVTYPE_CHEST", 20, { STR = 5 })
        local r = compare(W, weak)
        T.eq(r.isUpgrade, false) T.ok(r.delta < 0) T.eq(r.reason, W.EG.L.R_LOWER)
        local same = F.gear(W, 4003, "Twin Chestplate", "INVTYPE_CHEST", 30, { STR = 20, STA = 20 }, { armor = 300 })
        r = compare(W, same)
        T.near(r.delta, 0) T.eq(r.isUpgrade, false) T.eq(r.reason, W.EG.L.R_EQUAL)
    end)

    T.test("score: rings are compared with both slots, the larger gain wins", function()
        local W = arms()
        local ring = F.gear(W, 4004, "Good Ring", "INVTYPE_FINGER", 40, { STR = 20, HIT = 15 }, { typeText = "" })
        local r = compare(W, ring)
        T.near(r.score, 55) T.eq(r.mode, "EITHER") T.eq(r.candSlot, 12)
        T.near(r.targetScore, 14.5) T.near(r.delta, 40.5) T.eq(r.target.slotID, 12)
        T.eq(#r.equipped, 2)
        T.eq(r.slotName, "Finger 1 / Finger 2")
    end)

    T.test("score: an empty slot makes anything an improvement", function()
        local W = arms()
        W.equip(12, nil)
        local ring = F.gear(W, 4005, "Any Ring", "INVTYPE_FINGER", 10, { STA = 1 }, { typeText = "" })
        local r = compare(W, ring)
        T.eq(r.target.empty, true) T.eq(r.isUpgrade, true) T.eq(r.reason, W.EG.L.R_EMPTY)
        T.near(r.targetScore, 0)
    end)

    T.test("score: two-hand weapon replaces both hands", function()
        local W = arms()
        local axe = F.gear(W, 4006, "Big Axe", "INVTYPE_2HWEAPON", 40, {}, { dps = 30, typeText = "Axe" })
        local r = compare(W, axe)
        T.eq(r.mode, "BOTH") T.eq(r.combined, true) T.eq(r.candSlot, 16)
        T.near(r.score, 20 + 240) T.near(r.targetScore, 175) T.near(r.delta, 85)
        T.eq(r.isUpgrade, true)
        T.ok(r.note and r.note:find("two-handed", 1, true), "two-hand note")
    end)

    T.test("score: one-hand weapon may go to the off hand with half the weapon damage", function()
        local W = arms()
        local twin = F.gear(W, 4007, "New Sword", "INVTYPE_WEAPON", 30, {}, { dps = 20 })
        local r = compare(W, twin)
        T.eq(r.mode, "EITHER") T.eq(r.candSlot, 17)
        T.near(r.score, 15 + 20 * 8 * 0.5) T.near(r.delta, 95) T.eq(r.isUpgrade, true)
        W.state.player.dualWield = false
        W.EG:InvalidateAll()
        r = compare(W, twin)
        T.eq(r.mode, "SINGLE") T.near(r.delta, 0) T.eq(r.isUpgrade, false)
    end)

    T.test("score: a shield with a two-hander equipped costs the weapon", function()
        local W = arms(nil, function(w)
            local axe = F.gear(w, 4008, "Equipped Axe", "INVTYPE_2HWEAPON", 40, {}, { dps = 30, typeText = "Axe" })
            w.equip(16, axe)
        end)
        local shield = F.gear(W, 4009, "Tower Shield", "INVTYPE_SHIELD", 30, { STA = 30 }, { armor = 2000, typeText = "Shield" })
        local r = compare(W, shield)
        T.eq(r.mode, "BOTH") T.eq(r.candSlot, 17) T.eq(r.isUpgrade, false)
        T.ok(r.note and r.note:find("two-handed", 1, true))
    end)

    T.test("score: a shield with a one-hander compares against the empty off hand", function()
        local W = arms()
        local shield = F.gear(W, 4010, "Buckler", "INVTYPE_SHIELD", 30, { STA = 30 }, { armor = 2000, typeText = "Shield" })
        local r = compare(W, shield)
        T.eq(r.mode, "SINGLE") T.eq(r.isUpgrade, true) T.eq(r.target.empty, true)
        T.near(r.score, 15 + 3 + 2000 * 0.025)
    end)

    T.test("score: tanks only use the off hand for a weapon if one is already there", function()
        local W = T.world({ class = "WARRIOR", level = 60, talents = { mode = "specinfo", points = { 0, 0, 41 } } }, function(w)
            local s = F.gear(w, 4011, "Tank Sword", "INVTYPE_WEAPON", 30, {}, { dps = 20 })
            w.equip(16, s)
        end)
        local twin = F.gear(W, 4012, "Second Sword", "INVTYPE_WEAPON", 30, {}, { dps = 20 })
        local r = compare(W, twin)
        T.eq(W.EG.Profiles.Resolve().spec.id, "WARRIOR_PROT")
        T.eq(r.mode, "SINGLE", "protection keeps a shield slot")
    end)

    T.test("score: unique items cannot be doubled up", function()
        local W = arms(nil, function(w)
            local link = F.gear(w, 2002, "Copper Band", "INVTYPE_FINGER", 30, { STR = 10, CRIT = 10 }, { typeText = "", unique = true })
            w.equip(11, link)
        end)
        local r = compare(W, W.I.ring1)
        T.eq(r.target.slotID, 11, "the second copy replaces the first, not the weaker ring")
        T.ok(r.note and r.note:find("Unique", 1, true))
    end)

    T.test("score: level too low - would be an upgrade, but is not yet", function()
        local W = arms()
        local chest = F.gear(W, 4013, "Late Chest", "INVTYPE_CHEST", 70, { STR = 40 }, { minLevel = 65 })
        local r = compare(W, chest)
        T.eq(r.levelTooLow, true) T.eq(r.wouldUpgrade, true) T.eq(r.isUpgrade, false) T.eq(r.usable, true)
        T.eq(r.reason, string.format(W.EG.L.R_LEVEL, 65))
        T.eq(W.EG.Score.UpgradeState(chest), "LEVEL")
    end)

    T.test("score: items the client marks unusable never upgrade", function()
        local W = arms()
        local robe = F.gear(W, 4014, "Robe", "INVTYPE_CHEST", 90, { INT = 200 }, { badType = true, typeText = "Cloth" })
        local r = compare(W, robe)
        T.eq(r.usable, false) T.eq(r.isUpgrade, false) T.eq(r.reason, W.EG.L.R_CLASS)
        T.eq(W.EG.Score.UpgradeState(robe), nil)
    end)

    T.test("score: minimum gain - absolute and relative thresholds", function()
        local W = arms()
        local chest = F.gear(W, 4015, "Slightly Better", "INVTYPE_CHEST", 30, { STR = 24, STA = 20 }, { armor = 300 })
        local r = compare(W, chest)
        T.near(r.delta, 4) T.near(r.threshold, 0.445) T.eq(r.isUpgrade, true)
        W.EG:Set("minDeltaPercent", 10)
        r = compare(W, chest)
        T.near(r.threshold, 4.45) T.eq(r.isUpgrade, false) T.eq(r.wouldUpgrade, false)
        T.has(r.reason, "within noise")
        W.EG:Set("minDeltaPercent", 1) W.EG:Set("minDelta", 50)
        r = compare(W, betterChest(W))
        T.near(r.threshold, 50) T.eq(r.isUpgrade, false)
    end)

    T.test("score: shirts, tabards and non-gear are not compared", function()
        local W = arms()
        local tabard = F.gear(W, 4016, "Tabard", "INVTYPE_TABARD", 1, {})
        local r = compare(W, tabard)
        T.eq(r.noCompare, true) T.eq(r.isUpgrade, false)
        local potion = F.gear(W, 4017, "Potion", "", 1, {})
        r = compare(W, potion)
        T.eq(r.noCompare, true)
        T.eq(W.EG.Score.UpgradeState(potion), nil)
    end)

    T.test("score: a worthless item in an empty slot is not an improvement", function()
        local W = arms()
        W.equip(12, nil)
        local nothing = F.gear(W, 4030, "Nothing", "INVTYPE_FINGER", 0, {}, { typeText = "" })
        local r = compare(W, nothing)
        T.near(r.score, 0) T.near(r.delta, 0) T.eq(r.isUpgrade, false) T.eq(r.target.empty, true)
    end)

    T.test("score: stats the addon does not know count through a custom weight", function()
        local W = arms()
        local odd = W.item({ id = 4018, name = "Odd Ring", equipLoc = "INVTYPE_FINGER", ilvl = 30, quality = 3,
                             stats = { ITEM_MOD_FANCY_SHORT = 10 }, slotText = "Finger", typeText = "", type = "Armor", classID = 4 })
        local P = W.EG.Profiles
        T.near(W.EG.Score.OfLink(odd), 15, 1e-9)
        local id = P.CreateCustom("Fancy", "WARRIOR_ARMS")
        P.SetCustomWeight(id, "ITEM_MOD_FANCY_SHORT", 3)
        P.SetActive(id)
        T.near(W.EG.Score.OfLink(odd), 15 + 30)
        T.eq(W.EG.Items.Get(odd).unknown.ITEM_MOD_FANCY_SHORT, 10)
    end)

    T.test("score: empty sockets are worth a typical gem", function()
        local W = arms()
        local S = W.EG.Score
        local item = F.gear(W, 4019, "Socketed", "INVTYPE_HEAD", 30, {}, { sockets = 2 })
        local weights = W.EG.Profiles.Resolve().weights
        T.near(S.SocketPoints(weights), 60 * 0.22 * 1.0 * 0.9)
        T.near(S.OfLink(item), 15 + 2 * 60 * 0.22 * 0.9)
        W.EG:Set("socketValue", 5)
        T.near(S.OfLink(item), 15 + 10)
    end)

    T.test("score: item level share grows with the character level", function()
        local W = arms({ level = 30 })
        local eff, base, factor = W.EG.Score.EffectiveIlvlWeight()
        T.near(eff, 0.25) T.near(base, 0.5) T.near(factor, 0.5)
        W.EG:Set("ilvlScaling", false)
        T.near((W.EG.Score.EffectiveIlvlWeight()), 0.5)
        W.EG:Set("ilvlWeight", 0)
        T.near((W.EG.Score.EffectiveIlvlWeight()), 0)
    end)

    T.test("score: totals of the worn gear equal the sum of the single scores under any weights", function()
        local W = arms()
        local S, P = W.EG.Score, W.EG.Profiles
        local sum = 0
        for _, link in ipairs({ W.I.chest, W.I.ring1, W.I.ring2, W.I.trinket }) do sum = sum + S.OfLink(link) end
        sum = sum + S.Of(W.EG.Items.Get(W.I.sword), 16)
        local totals = S.EquippedTotals(true)
        local _, total = S.TotalsBreakdown(totals, P.Resolve().weights)
        T.near(total, sum, 1e-9)
        T.near(sum, 301.5)
        T.eq(totals.COUNT, 5)
        local other = P.WeightsFor(W.EG.Specs.BY_ID.WARRIOR_PROT)
        local _, t2 = S.TotalsBreakdown(totals, other)
        local direct = 0
        W.EG.Profiles.SetActive("WARRIOR_PROT")
        for _, link in ipairs({ W.I.chest, W.I.ring1, W.I.ring2, W.I.trinket }) do direct = direct + S.OfLink(link) end
        direct = direct + S.Of(W.EG.Items.Get(W.I.sword), 16)
        T.near(t2, direct, 1e-9)
    end)

    T.test("score: equipment changes re-aim the comparison after a short delay", function()
        local W = arms()
        local chest = betterChest(W)
        T.near(compare(W, chest).targetScore, 44.5)
        W.equip(5, F.gear(W, 4020, "Mid Chest", "INVTYPE_CHEST", 36, { STR = 25 }, { armor = 400 }))
        W.fire("PLAYER_EQUIPMENT_CHANGED", 5)
        T.near(compare(W, chest).targetScore, 44.5, 1e-9, "cached until the delay is over")
        W.flush()
        T.near(compare(W, chest).targetScore, 18 + 25 + 10)
    end)

    T.test("score: UpgradeState reports pending data", function()
        local W = arms()
        local slow = F.gear(W, 4021, "Slow Chest", "INVTYPE_CHEST", 50, { STR = 50 }, { uncached = true })
        local state, pending = W.EG.Score.UpgradeState(slow)
        T.eq(state, nil) T.eq(pending, true)
        W.state.items[4021].uncached = nil
        T.eq(W.EG.Score.UpgradeState(slow), "UPGRADE")
        T.eq(W.EG.Score.UpgradeState(nil), nil)
    end)

    T.test("score: a worn item that is not loaded yet makes the comparison wait", function()
        local W = arms()
        W.state.items[2001].uncached = true
        W.EG.Items.Wipe()
        local fresh = F.gear(W, 4022, "Fresh Chest", "INVTYPE_CHEST", 50, { STR = 50 })
        local r, why = W.EG.Score.Compare(fresh)
        T.eq(r, nil) T.eq(why, "loading")
        local state, pending = W.EG.Score.UpgradeState(fresh)
        T.eq(state, nil) T.eq(pending, true)
    end)

    T.test("score: slot names are numbered when both slots share a name", function()
        local W = arms()
        local S = W.EG.Score
        T.eq(S.SlotName(11), "Finger 1") T.eq(S.SlotName(12), "Finger 2")
        T.eq(S.SlotName(5), "Chest") T.eq(S.SlotName({ 16, 17 }), "Main Hand / Off Hand")
        T.eq(S.SlotName(nil), "?")
    end)
end
