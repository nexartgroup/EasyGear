-- Slash.lua: chat commands and reports
return function(T)
    local F = require("fixtures")

    local function world(setup, opts)
        return T.world(F.arms(opts), function(W)
            W.I = F.armsWarrior(W)
            W.I.better = F.gear(W, 9101, "Better Chestplate", "INVTYPE_CHEST", 40, { STR = 30, STA = 40, CRIT = 20 }, { armor = 500, minLevel = 35, sellPrice = 77 })
            W.I.ring = F.gear(W, 9102, "Good Ring", "INVTYPE_FINGER", 40, { STR = 20, HIT = 15 }, { typeText = "" })
            if setup then setup(W) end
        end)
    end
    -- chat text without color codes (item links keep their |H...|h[Name]|h part)
    local function say(W, msg)
        W.clearChat()
        W.slash(msg)
        return (W.chatText():gsub("|c%x%x%x%x%x%x%x%x", ""):gsub("|r", ""))
    end

    T.test("slash: the commands are registered", function()
        local W = world()
        T.ok(W.env.SlashCmdList.EASYGEAR and W.env.SlashCmdList.EASYGEARGUI and W.env.SlashCmdList.EASYGEARPROFILE)
        T.eq(W.env.SLASH_EASYGEAR1, "/eg") T.eq(W.env.SLASH_EASYGEAR2, "/easygear")
        T.eq(W.env.SLASH_EASYGEARGUI1, "/eggui") T.eq(W.env.SLASH_EASYGEARPROFILE1, "/egprofile")
        W.env.SlashCmdList.EASYGEARGUI()
        T.eq(W.EG.Window.IsShown(), true)
        W.env.SlashCmdList.EASYGEARPROFILE()
        T.eq(W.EG.ProfileWindow.IsShown(), true)
    end)

    T.test("slash: /eg toggles the window, help lists every command", function()
        local W = world()
        W.slash("")
        T.eq(W.EG.Window.IsShown(), true)
        W.slash("gui")
        T.eq(W.EG.Window.IsShown(), false)
        local text = say(W, "help")
        for _, cmd in ipairs({ "/eg upgrades", "/eggui", "/egprofile", "/eg profile list", "/eg weight", "/eg ilvl", "/eg status", "/eg reset", "/eg parse", "/eg unknown" }) do
            T.has(text, cmd)
        end
        T.hasnt(text, "H_", "every description resolves to text")
    end)

    T.test("slash: a link gives a full report and fills the window", function()
        local W = world()
        local text = say(W, "look at " .. W.I.better .. " please")
        T.has(text, "===== EasyGear =====") T.has(text, "Better Chestplate") T.has(text, "Arms (two-hand) (Automatic)")
        T.has(text, "Item level: 40") T.has(text, "Slot: Chest") T.has(text, "Required level: 35")
        T.has(text, "Armor                         500  x 0.025  = 12.5", "weights keep their third decimal")
        T.has(text, "Vendor price: 77c")
        T.has(text, "Strength") T.has(text, "Worn Chestplate")
        T.has(text, "Difference: +37") T.has(text, ">> UPGRADE")
        T.eq(W.EG.Window.IsShown(), true)
        T.eq(W.EG.Window.Link(), W.I.better)
    end)

    T.test("slash: a bare item id works, an unknown or unloaded one says so", function()
        local W = world()
        T.has(say(W, "9101"), "Better Chestplate")
        T.has(say(W, "123456"), "not cached yet")
        W.I.slow = F.gear(W, 9103, "Slow", "INVTYPE_CHEST", 40, { STR = 1 }, { uncached = true })
        T.has(say(W, "9103"), "not cached yet")
    end)

    T.test("slash: reports for unusable items and items that are not compared", function()
        local W = world()
        local robe = F.gear(W, 9104, "Robe", "INVTYPE_CHEST", 90, { INT = 100 }, { badType = true, typeText = "Cloth" })
        T.has(say(W, "9104"), "NOT USABLE")
        local tabard = F.gear(W, 9105, "Tabard", "INVTYPE_TABARD", 1, {})
        T.hasnt(say(W, "9105"), "Currently equipped")
        local late = F.gear(W, 9106, "Late", "INVTYPE_CHEST", 90, { STR = 100 }, { minLevel = 65 })
        T.has(say(W, "9106"), "UPGRADE from level 65")
        local _ = robe, tabard, late
    end)

    T.test("slash: /eg upgrades lists the bags best first, or says there are none", function()
        local W = world()
        T.has(say(W, "upgrades"), "No upgrades in your bags.")
        W.put(0, 1, W.I.better) W.put(0, 2, W.I.ring)
        local text = say(W, "upgrades")
        T.has(text, "Upgrades in your bags (best first)")
        local ringPos, chestPos = text:find("Good Ring", 1, true), text:find("Better Chestplate", 1, true)
        T.ok(ringPos and chestPos and ringPos < chestPos, "the bigger gain comes first")
        T.has(text, "+40.5") T.has(text, "Finger 2")
    end)

    T.test("slash: profile commands", function()
        local W = world()
        local text = say(W, "profile list")
        T.has(text, "Available profiles") T.has(text, "AUTO") T.has(text, "WARRIOR_ARMS") T.has(text, ">>")
        T.has(say(W, "profile warrior_prot"), "Active profile: Protection (tank)")
        T.eq(W.EG.Profiles.ActiveID(), "WARRIOR_PROT")
        T.has(say(W, "profile auto"), "Active profile: Arms")
        T.eq(W.EG.Profiles.ActiveID(), "AUTO")
        text = say(W, "profile nonsense")
        T.has(text, "Unknown profile: nonsense") T.has(text, "Available profiles")
        W.slash("profile gui")
        T.eq(W.EG.ProfileWindow.IsShown(), true)
        local id = W.EG.Profiles.CreateCustom("Mixed Case", "WARRIOR_ARMS")
        T.has(say(W, "profile " .. id), "Active profile: Mixed Case")
        W.EG.Profiles.SetActive("AUTO")
        T.has(say(W, "profile custom_mixedcase"), "Active profile: Mixed Case", "ids are matched without regard to case")
        T.eq(W.EG.Profiles.ActiveID(), id)
    end)

    T.test("slash: /eg weight edits the active own profile only", function()
        local W = world()
        T.has(say(W, "weight CRIT 2"), "built in")
        local id = W.EG.Profiles.CreateCustom("Mine", "WARRIOR_ARMS")
        W.EG.Profiles.SetActive(id)
        T.has(say(W, "weight CRIT 2,5"), "CRIT = 2.5")
        T.eq(W.EG.Profiles.Get(id).weights.CRIT, 2.5)
        T.has(say(W, "weight crit 1"), "CRIT = 1")
        T.eq(W.EG.Profiles.Get(id).weights.CRIT, 1)
        T.has(say(W, "weight ITEM_MOD_FANCY_SHORT 3"), "ITEM_MOD_FANCY_SHORT = 3")
        T.eq(W.EG.Profiles.Get(id).weights.ITEM_MOD_FANCY_SHORT, 3)
        T.has(say(W, "weight CRIT"), "Usage")
        T.has(say(W, "weight CRIT abc"), "Usage")
    end)

    T.test("slash: numbers and switches", function()
        local W = world()
        T.has(say(W, "ilvl 0.8"), "0.8") T.eq(W.EG:Get("ilvlWeight"), 0.8)
        say(W, "ilvl -3") T.eq(W.EG:Get("ilvlWeight"), 0.8, "negative values are refused")
        say(W, "ilvl abc") T.eq(W.EG:Get("ilvlWeight"), 0.8)
        T.has(say(W, "ilvlscale off"), "disabled") T.eq(W.EG:Get("ilvlScaling"), false)
        T.has(say(W, "ilvlscale"), "enabled") T.eq(W.EG:Get("ilvlScaling"), true)
        say(W, "mindelta 3") T.eq(W.EG:Get("minDelta"), 3)
        say(W, "mindeltapct 5") T.eq(W.EG:Get("minDeltaPercent"), 5)
        T.has(say(W, "mindelta"), "Minimum difference: 3 points (+ 5% relative)")
        say(W, "socket 7") T.eq(W.EG:Get("socketValue"), 7)
        T.has(say(W, "socket auto"), "Automatic") T.eq(W.EG:Get("socketValue"), nil)
        say(W, "autolevel off") T.eq(W.EG:Get("autoLeveling"), false)
        say(W, "autolevel off") T.eq(W.EG:Get("autoLeveling"), false, "off stays off")
        say(W, "autolevel on") T.eq(W.EG:Get("autoLeveling"), true)
        say(W, "autolevel on") T.eq(W.EG:Get("autoLeveling"), true, "on stays on")
        say(W, "autolevel aus") T.eq(W.EG:Get("autoLeveling"), false, "German words work")
        say(W, "autolevel an") T.eq(W.EG:Get("autoLeveling"), true)
        say(W, "enchants off") T.eq(W.EG:Get("includeEnchants"), false)
    end)

    T.test("slash: toggles flip the settings", function()
        local W = world()
        for cmd, key in pairs({ icons = "showBagIcons", items = "showItemIcons", quest = "showQuestIcons",
                                char = "showCharIcons", tooltip = "showTooltip", stats = "showTooltipStats", diff = "tooltipDiff" }) do
            local before = W.EG:Get(key)
            say(W, cmd)
            T.eq(W.EG:Get(key), not before, cmd)
            say(W, cmd .. (before and " on" or " off"))
            T.eq(W.EG:Get(key), before, cmd .. " explicit")
        end
    end)

    T.test("slash: status shows profile, talents, settings and the interface hooks", function()
        local W = world()
        local text = say(W, "status")
        T.has(text, "EasyGear 4.0.0-test") T.has(text, "Profile: Arms (two-hand) (Automatic)  [AUTO]")
        T.has(text, "Client: 1.60.1 (70862)  interface 16001")
        T.has(text, "Talent points: 40 / 5 / 0  (specinfo)")
        T.has(text, "Item level weight: 0.5 -> 0.5") T.has(text, "Interface hooks:")
        T.has(text, "itembuttons") T.has(text, "tooltip") T.hasnt(text, "WoW Forever client")
        W.EG.hookStatus.broken = { ok = false, note = "gone" }
        T.has(say(W, "status"), "broken (gone)")
        W.EG.lastError = { label = "x", err = "boom" }
        T.has(say(W, "status"), "Last error: [x] boom")
    end)

    T.test("slash: parse shows what was read from an item", function()
        local W = world()
        local text = say(W, "parse " .. W.I.better)
        T.has(text, "Item analysis") T.has(text, "equipLoc=INVTYPE_CHEST") T.has(text, "base: ARMOR=500")
        T.has(text, "STR=30") T.has(text, "unknown: -")
        T.has(say(W, "parse"), "Usage")
        T.has(say(W, "parse 9101"), "Item analysis")
        local potion = F.gear(W, 9107, "Potion", "", 1, {})
        T.hasnt(say(W, "parse 9107"), "usable=")
    end)

    T.test("slash: unknown lists stats the addon cannot score", function()
        local W = world()
        T.has(say(W, "unknown"), "All stats on your gear and in your bags are known.")
        local odd = W.item({ id = 9108, name = "Odd", equipLoc = "INVTYPE_FINGER", ilvl = 30, quality = 3,
                             stats = { ITEM_MOD_FANCY_SHORT = 10 }, slotText = "Finger", typeText = "", type = "Armor", classID = 4 })
        W.put(0, 1, odd)
        local text = say(W, "unknown")
        T.has(text, "ITEM_MOD_FANCY_SHORT  x1") T.has(text, "/eg weight")
    end)

    T.test("slash: locale shows the active language file and coverage", function()
        local W = world()
        local text = say(W, "locale")
        T.has(text, "Client language: enUS") T.has(text, "enUS.lua")
        local W2 = world(nil, { locale = "frFR" })
        W2.clearChat()
        W2.slash("locale")
        T.has(W2.chatText(), "frFR.lua") T.has(W2.chatText(), "Translated texts:")
    end)

    T.test("slash: scale and reset", function()
        local W = world()
        T.has(say(W, "scale 1.25"), "1.25") T.eq(W.env.EasyGearCharDB.gui.scale, 1.25)
        say(W, "scale 5") T.eq(W.env.EasyGearCharDB.gui.scale, 1.25, "out of range is ignored")
        W.EG:Set("showTooltip", false)
        local id = W.EG.Profiles.CreateCustom("Keep", "WARRIOR_ARMS")
        W.EG.Profiles.SetActive("WARRIOR_PROT")
        T.has(say(W, "reset"), "reset to defaults")
        T.eq(W.EG:Get("showTooltip"), true) T.eq(W.EG.Profiles.ActiveID(), "AUTO")
        T.eq(W.env.EasyGearCharDB.gui.scale, 1)
        T.ok(W.EG.Profiles.Get(id), "own profiles are kept")
    end)

    T.test("slash: options opens the settings page; unknown words print the help", function()
        local W = world()
        W.slash("options")
        T.eq(#W.state.opened, 1)
        T.has(say(W, "frobnicate"), "/eg upgrades")
    end)

    T.test("slash: an error inside a command is contained", function()
        local W = world()
        W.EG.Slash.PrintStatus = function() error("kaputt") end
        W.slash("status")
        T.ok(tostring(W.EG.lastError.err):find("kaputt", 1, true))
    end)

    T.test("slash: numbers outside their range or not numbers are refused with a hint", function()
        local W = world()
        for _, def in ipairs({
            { "ilvl", "ilvlWeight", { "-1", "11", "abc", "nan", "inf", "-inf" }, "0 to 10" },
            { "mindelta", "minDelta", { "-1", "1001", "abc", "inf" }, "0 to 1000" },
            { "mindeltapct", "minDeltaPercent", { "-1", "101", "abc" }, "0 to 100" },
            { "socket", "socketValue", { "-1", "1001", "abc" }, "0 to 1000" },
        }) do
            local before = W.EG:Get(def[2])
            for _, bad in ipairs(def[3]) do
                local text = say(W, def[1] .. " " .. bad)
                T.has(text, "Please enter a number from " .. def[4], def[1] .. " " .. bad)
                T.eq(W.EG:Get(def[2]), before, def[1] .. " " .. bad .. " changes nothing")
            end
        end
        T.hasnt(say(W, "ilvl"), "Please enter", "no argument just shows the value")
        T.has(say(W, "scale 3"), "Please enter a number from 0.5 to 2")
        T.eq(W.env.EasyGearCharDB.gui.scale, 1)
        T.hasnt(say(W, "ilvl 0"), "Please enter") T.eq(W.EG:Get("ilvlWeight"), 0, "the limits themselves are valid")
        say(W, "ilvl 10") T.eq(W.EG:Get("ilvlWeight"), 10)
        say(W, "mindeltapct 100") T.eq(W.EG:Get("minDeltaPercent"), 100)
        say(W, "socket 0") T.eq(W.EG:Get("socketValue"), 0)
        say(W, "socket 1,5") T.eq(W.EG:Get("socketValue"), 1.5, "a decimal comma works")
    end)

    T.test("slash: weights refuse nan and infinity", function()
        local W = world()
        local id = W.EG.Profiles.CreateCustom("Mine", "WARRIOR_ARMS")
        W.EG.Profiles.SetActive(id)
        local before = W.EG.Profiles.Get(id).weights.CRIT
        for _, bad in ipairs({ "nan", "inf", "-inf" }) do
            T.has(say(W, "weight CRIT " .. bad), "Usage")
            T.eq(W.EG.Profiles.Get(id).weights.CRIT, before)
        end
    end)

    T.test("slash: item strings and plain ids are accepted, other numbers are not items", function()
        local W = world()
        T.has(say(W, "item:9101"), "Better Chestplate")
        T.has(say(W, "item:9101:0:0:0:0:0:0:0:60"), "Better Chestplate")
        T.has(say(W, "parse item:9101"), "equipLoc=INVTYPE_CHEST")
        T.has(say(W, "parse 9101"), "equipLoc=INVTYPE_CHEST")
        W.EG.Window.Clear()
        for _, junk in ipairs({ "0", "-5", "1.5" }) do
            T.has(say(W, junk), "/eg upgrades", junk .. " shows the help")
        end
        T.eq(W.EG.Window.Link(), nil, "none of them reached the window")
    end)

    T.test("slash: the chat report comes first - an error in the window does not take it away", function()
        local W = world()
        W.EG.Window.SetItem = function() error("window broke") end
        local text = say(W, "9101")
        T.has(text, "===== EasyGear =====") T.has(text, ">> UPGRADE")
        T.has(text, "window broke", "the problem is reported as well")
    end)
end
